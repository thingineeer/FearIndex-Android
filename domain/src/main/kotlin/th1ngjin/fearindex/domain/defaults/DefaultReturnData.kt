    private fun r(m1: Double, m3: Double, m6: Double, y1: Double) =
        HistoricalReturns(oneMonth = m1, threeMonth = m3, sixMonth = m6, oneYear = y1)

    private fun c(m1: Int, m3: Int, m6: Int, y1: Int) =
        HistoricalSampleCounts(oneMonth = m1, threeMonth = m3, sixMonth = m6, oneYear = y1)

    private fun dp(
        score: Int,
        ret: HistoricalReturns,
        worst: HistoricalReturns,
        best: HistoricalReturns,
        count: Int,
        counts: HistoricalSampleCounts? = null,
    ) = ReturnDataPoint(
        score = score,
        returns = ret,
        worstCase = worst,
        bestCase = best,
        sampleCount = count,
        horizonSampleCounts = counts ?: HistoricalSampleCounts.same(count),
    )

    private fun zeroDp(score: Int) = dp(score, r(0.0, 0.0, 0.0, 0.0), r(0.0, 0.0, 0.0, 0.0), r(0.0, 0.0, 0.0, 0.0), 0)

    private fun ev(id: String, date: Instant, score: Int, key: String, ret: HistoricalReturns? = null) =
        ReturnEventEntry(id = id, date = date, score = score, descriptionKey = key, returnAfter = ret)

    private fun d(year: Int, month: Int, day: Int): Instant =
        LocalDate.of(year, month, day).atStartOfDay(ZoneOffset.UTC).toInstant()

    private fun range(from: String, to: String): DateRange =
        DateRange(start = LocalDate.parse(from).atStartOfDay(ZoneOffset.UTC).toInstant(),
            end = LocalDate.parse(to).atStartOfDay(ZoneOffset.UTC).toInstant())

